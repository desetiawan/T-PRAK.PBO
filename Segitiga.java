package tugaspraktikum2;

public class Segitiga {
    public static void main(String[] args) {
        double a = 6; // tinggi
        double b = 8; // alas

        double luas = 0.5 * b * a;
        System.out.println("Alas (b): " + b);
        System.out.println("Tinggi (a): " + a);
        System.out.println("Luas Segitiga: " + luas);
    }
}
