package P7;

public class SumpahPemuda {
    private String pembuka;

    public SumpahPemuda() {
        pembuka = "Kami putra dan putri Indonesia";
        System.out.println("=== SUMPAH PEMUDA ===");
        System.out.println(pembuka);
    }

    public void sumpahPertama() {
        System.out.println("Pertama : mengaku bertumpah darah yang satu, tanah air Indonesia.");
    }

    public void sumpahKedua() {
        System.out.println("Kedua   : mengaku berbangsa yang satu, bangsa Indonesia.");
    }

    public void sumpahKetiga() {
        System.out.println("Ketiga  : menjunjung bahasa persatuan, bahasa Indonesia.");
    }
}
